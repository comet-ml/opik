import { test, expect } from '@e2e/fixtures';
import type { JudgeMessageWrite, JudgeOutputSchemaType } from '@e2e/core/backend';
import { OnlineEvaluationPage } from '@e2e/pom/online-evaluation.page';
import { fetchRegistryModels, pickRegistryStoredValuePair } from '@e2e/core/model-registry';

/**
 * A judge rule on a VERTEX AI model id the picker no longer lists (opik#9648).
 *
 * `online-evaluation-orphaned-judge-model.spec.ts` already asserts the
 * raw-value fallback in `PromptModelSelect` — a stored id no option list offers
 * must hydrate end-anchored rather than going blank. It drives `anthropic` and
 * `openrouter`. This one drives `vertex-ai`, and it is a structurally different
 * vector rather than a third row of the same matrix:
 *
 *  - **A vertex row's stored value is not its id.** `transformFetched` composes
 *    every dropdown value as `getRoutableProviderModelValue(provider,
 *    qualified_name || id)`, whose only special case is Vertex: the value is
 *    provider-qualified (`vertex_ai/gemini-3.6-flash`). On anthropic and
 *    openrouter the stored value and the id are the same string, so that spec's
 *    pick — which returns `id` — is the right answer there and the wrong one
 *    here. A fallback that rendered the bare id would be a different, quieter
 *    failure than a blank picker, and only a spec that knows the qualified
 *    spelling can see it.
 *  - **Here a plausible WRONG answer exists.** The `gemini` provider still
 *    labels a row with the BARE id that this vertex row carries qualified, so
 *    "Gemini 3.6 Flash" is a substitution a loosely-resolving picker could make
 *    — and on anthropic/openrouter there is no such look-alike to substitute.
 *    An end-anchored match on the full `vertex_ai/...` value excludes it, along
 *    with the blank placeholder and a truncation to the bare id.
 *
 * opik#9648 is what made this reachable: the sync dropped the `label` from the
 * vertex `gemini-3.6-flash` row while leaving the enum and the registry row in
 * place, which is exactly the shape that orphans a saved rule. The consequence
 * of the fallback going away is not cosmetic — the user's next ordinary save,
 * which they believe leaves the model alone, writes whatever the form had
 * instead, so the rule silently starts judging with a different model at a
 * different price.
 *
 * The CONTROL is what makes this a result rather than a shrug. A second rule is
 * seeded on a vertex row that IS labelled, and its picker must read the LABEL,
 * not the stored value. Without it, "the picker shows the stored id" is equally
 * satisfied by a trigger that echoes every value it is given and resolves
 * nothing — which would mean the fallback never ran and the spec proved nothing.
 *
 * Deterministic and LLM-free by construction: both rules are seeded disabled at
 * `sampling_rate: 0`, so neither can ever reach a provider. That matters on this
 * environment specifically — no LLM provider on the staging workspace answers —
 * and it is why this spec runs anywhere rather than only where a Vertex key is
 * configured.
 *
 * The ids are picked from the deployment's registry at runtime, never pinned:
 * which rows carry a label is regenerated by `scripts/sync_provider_models.py`
 * on every sync, so a pinned id that regained its label would turn this into a
 * check of the label.
 */

/** The provider whose stored values are provider-qualified. See the header. */
const PROVIDER = 'vertex-ai';

/** The prefix a vertex stored value must carry — the premise of this spec. */
const VERTEX_PREFIX = 'vertex_ai/';

/** What the trigger reads when nothing is selected — the failure, not the expectation. */
const EMPTY_PICKER_TEXT = 'Select an LLM model';

/**
 * The trigger text a stored value must produce, end-anchored.
 *
 * `getSelectedModelInfo` renders `<provider label> <modelName>` on the
 * non-compact trigger and the bare `modelName` on the compact one, so the
 * expected string is anchored at the END: that admits either shape while still
 * being exact about the value itself.
 *
 * Anchoring is load-bearing rather than tidiness. For the orphan it is what
 * excludes the three ways this breaks — a blank picker, a truncation to the
 * bare `gemini-3.6-flash`, and a substitution of the gemini provider's
 * similarly-named label — none of which a `toContainText` would catch. For the
 * control it is what stops the LABEL assertion being satisfied by a trigger
 * that rendered the raw stored value instead.
 */
function pickerShows(text: string): RegExp {
  const escaped = text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|\\s)${escaped}$`);
}

const JUDGE_MESSAGES: JudgeMessageWrite[] = [
  {
    role: 'USER',
    content: 'Is the OUTPUT non-empty?\n\nOUTPUT:\n{{output}}',
  },
];

const JUDGE_VARIABLES = { output: 'output.output' };

const JUDGE_SCHEMA: Array<{
  name: string;
  type: JudgeOutputSchemaType;
  description: string;
}> = [
  {
    name: 'Non empty',
    type: 'BOOLEAN',
    description: 'Returns true when the output is non-empty',
  },
];

test.describe(
  'Online Evaluation — a Vertex AI judge model the picker no longer lists',
  { tag: ['@t2-cuj', '@area:online-evaluation'] },
  () => {
    test(
      'A vertex-ai id stored as its qualified name hydrates verbatim, while a labelled sibling resolves to its label',
      { tag: ['@cap:online-evaluation.edit-rule'] },
      async ({ project, backendClient, testNamespace, automationRulesCleanup, page }) => {
        const pair = await test.step(
          'Pick a listed and an unlisted vertex-ai row from the deployment registry',
          async () => pickRegistryStoredValuePair(await fetchRegistryModels(), PROVIDER),
        );

        await test.step('The pair really has the shape this spec is about (seed shape)', async () => {
          // Asserted before anything is seeded, because every claim below rests
          // on it. A deployment whose vertex rows stopped being
          // provider-qualified, or whose labelled row's label happened to equal
          // its stored value, would make the orphan assertion a check of the
          // bare id and the control assertion a tautology — both of which would
          // still go green and read as coverage.
          expect(
            pair.unlistedValue,
            `a vertex stored value is provider-qualified, which is what makes this vector ` +
              `different from the anthropic/openrouter ones; got '${pair.unlistedValue}'`,
          ).toContain(VERTEX_PREFIX);
          expect(
            pair.listedValue,
            `the control's stored value is provider-qualified too; got '${pair.listedValue}'`,
          ).toContain(VERTEX_PREFIX);
          expect(
            pair.unlistedValue,
            'the orphan and the control must be different rows, or there is no comparison',
          ).not.toBe(pair.listedValue);
          expect(
            pair.listedLabel,
            `the control's label must differ from its stored value ('${pair.listedValue}'), ` +
              'or "the picker resolved a label" cannot be told from "the picker echoed the value"',
          ).not.toBe(pair.listedValue);
        });

        const seeded = await test.step('Seed a disabled judge rule on each stored value', async () => {
          const vectors = [
            { key: 'orphan', model: pair.unlistedValue, expected: pair.unlistedValue },
            { key: 'control', model: pair.listedValue, expected: pair.listedLabel },
          ];
          return Promise.all(
            vectors.map(async (vector) => {
              const name = `${testNamespace}-vertex-${vector.key}`;
              const id = await backendClient.createLlmJudgeRule({
                projectId: project.id,
                name,
                // Disabled AND at a zero sampling rate: either alone would stop
                // it scoring, and both together mean a rule that cannot reach a
                // provider even if one of the two were mis-read. No provider on
                // this workspace answers, so a rule that could fire would be a
                // flake rather than a finding.
                enabled: false,
                samplingRate: 0,
                model: vector.model,
                temperature: 0,
                messages: JUDGE_MESSAGES,
                variables: JUDGE_VARIABLES,
                schema: JUDGE_SCHEMA,
              });
              return { ...vector, name, id };
            }),
          );
        });

        await test.step('Each rule really stored the qualified id it was seeded with', async () => {
          // Before the browser opens. A backend that normalised the
          // `vertex_ai/` prefix away would make every assertion below a test of
          // the wrong string, and it would read as coverage of a fallback that
          // never ran.
          for (const rule of seeded) {
            const model = await backendClient.getLlmJudgeModel(rule.id);
            expect(model.name, `the ${rule.key} rule stores '${rule.model}' verbatim`).toBe(
              rule.model,
            );
          }
        });

        const onlineEval = new OnlineEvaluationPage(page);

        await test.step('Open the Online evaluation page', async () => {
          await onlineEval.goto(project.id);
          await onlineEval.waitForReady();
          for (const rule of seeded) {
            await expect(onlineEval.ruleRow(rule.name)).toHaveCount(1);
          }
        });

        for (const rule of seeded) {
          await test.step(`The '${rule.key}' rule's picker reads exactly '${rule.expected}'`, async () => {
            await onlineEval.openEditRulePanelByName(rule.name);
            // `toHaveText` retries, so a picker that hydrates once the model
            // query resolves is waited for rather than raced — which also means
            // the orphan's assertion cannot be satisfied by the placeholder
            // that is on screen before hydration.
            await expect(
              onlineEval.modelPicker,
              rule.key === 'orphan'
                ? `an id in no option list must fall back to the stored value — not '${EMPTY_PICKER_TEXT}', ` +
                    'not the bare id with the vertex_ai/ prefix dropped, and not the gemini ' +
                    "provider's similarly-named label"
                : 'a LISTED row must resolve to its label, which is what proves the orphan above ' +
                    'took the fallback rather than the trigger echoing every value it is given',
            ).toHaveText(pickerShows(rule.expected));
            await onlineEval.cancelPanel();
          });
        }

        await test.step('Closing without saving left both stored models untouched', async () => {
          // Opening the editor hydrates the form from the rule; a form that
          // could not map its own hydrated value is how an unrelated save
          // rewrites the judge model. Cancelling must write nothing at all.
          for (const rule of seeded) {
            const model = await backendClient.getLlmJudgeModel(rule.id);
            expect(
              model.name,
              `opening and cancelling the '${rule.key}' editor must not write`,
            ).toBe(rule.model);
          }
        });
      },
    );
  },
);

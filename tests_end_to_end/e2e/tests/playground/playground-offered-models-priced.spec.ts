import * as fs from 'node:fs';
import * as path from 'node:path';
import { test, expect } from '@e2e/fixtures';
import { fetchRegistryModels, listsInPicker } from '@e2e/core/model-registry';

/**
 * Every OpenRouter model a user can SELECT has a row in the price file the
 * backend resolves cost from (opik#9585, 2.2.146).
 *
 * 9585 regenerated `model_prices_openrouter.json` and dropped 21 ids from it.
 * The release report's worry was the silent half of that: not a model that
 * stops working, but one a user can still pick whose spans then cost nothing,
 * for as long as nobody checks a bill. Nothing in the estate crosses the two
 * artifacts — the 16 specs on `traces.span-model-cost-tokens` each pin an
 * AMOUNT for a handful of hand-named ids, which says nothing about the 369
 * models the picker offers and which is also why three of
 * `openrouter-repriced-spans.fixture.ts`'s four pins were stale by this
 * release. This pins a RELATION instead, so a regen that moves every rate
 * leaves it green and a regen that removes a row does not.
 *
 * ## Why the catalog comes from the deployment and the prices from the checkout
 *
 * The offered set is a fact about the DEPLOYMENT: `GET /v1/private/llm/models`
 * is what `useLLMProviderModelsData` fetches on mount, and the frontend filters
 * every dropdown with `isDropdownVisible = Boolean(m.label)` — so what a user
 * can pick is the labelled half of that payload and nothing else. (The 2.2.146
 * release audit reasoned from `PROVIDER_MODEL_TYPE` in `types/providers.ts`
 * instead and concluded 21 selectable models had lost their price; all 21 are
 * in fact served UNLABELLED and offered nowhere. That enum is dead code for the
 * picker — `constants/providerModels.ts` says so in its own doc comment.)
 *
 * The price rows are a fact about the BUILD, and there is no endpoint that
 * serves them: `ModelPriceTable` reads the resource file at startup and the
 * only way to observe a row through the API is to log a span and read the cost
 * back. That route cannot answer this question, for two independent reasons
 * found while writing this spec:
 *
 *  - A row with zero rates and NO ROW AT ALL both come back with
 *    `total_estimated_cost` absent. `gemini/gemma-4-26b-a4b-it` and
 *    `gemini/gemma-4-31b-it` are offered, are priced at 0.0/0.0 in the shipped
 *    file, and read back exactly like an id in no row — so "resolves a cost"
 *    cannot distinguish "priced free" from "unpriced".
 *  - For OpenRouter specifically the resolver cannot find its own rows:
 *    `CostService.parseModelName` strips to the first slash on the price key
 *    and on the span's model alike, so a three-segment key lands two-segment
 *    while the two-segment id Opik itself writes strips one segment too far.
 *    That defect is already reproduced and pinned by
 *    `openrouter-span-cost.spec.ts`'s second test; it means a span-cost probe
 *    of the offered OpenRouter catalog would report all 369 unpriced whatever
 *    the file contained.
 *
 * So the file is read directly. The cost of that is a checkout the deployment
 * does not match: a model staging offers because it is AHEAD of this checkout
 * has no row here and reads as a miss. The failure message says so, because
 * that is the first thing to rule out before calling a red here a defect.
 *
 * ## Why OpenRouter only
 *
 * Because OpenRouter is the one provider whose key spelling is a relation
 * rather than a lookup. Every labelled OpenRouter id `X` is keyed
 * `openrouter/X`, uniformly, all 369 of them. The four curated providers are
 * not: of 69 labelled ids, some are keyed bare, some under `gemini/`, and two
 * (`vertex_ai/gemini-2.5-pro`, `vertex_ai/gemini-2.5-flash`) are under no
 * spelling of their own at all and resolve only through
 * `findModelPriceUnderProvider`'s normalising ladder and
 * `ProviderRegistry.priceLookupOrder`. Reproducing that ladder here would be
 * a paraphrase of the resolver that goes stale the moment it changes, and a
 * naive key check over those four reports false misses — which is why they are
 * deliberately out of scope. See the taxonomy note.
 */

/**
 * The price file the BACKEND resolves cost from.
 *
 * `apps/opik-frontend/src/data/model_prices_openrouter.json` is a second copy,
 * regenerated by the same script in the same commit, and the frontend uses it
 * for its own display estimates. The backend's is the one that decides what a
 * span is billed, which is the thing a missing row loses — so that is the copy
 * this asserts against.
 */
const OPENROUTER_PRICE_FILE = path.resolve(
  __dirname,
  '../../../../apps/opik-backend/src/main/resources/model_prices_openrouter.json',
);

/** The provider key the registry serves OpenRouter's catalog under. */
const PROVIDER = 'openrouter';

/**
 * How `model_prices_openrouter.json` keys a model the registry calls `id`.
 *
 * One relation, applied to every row — not a search over spellings. A search
 * would also pass when an id happened to collide with a main-price-file key
 * under another vendor, which is a different model at a different price; 20 of
 * the 369 labelled ids do have such a bare twin.
 */
const priceKeyFor = (registryId: string): string => `${PROVIDER}/${registryId}`;

test.describe('Playground — the offered OpenRouter catalog is priced', {
  tag: ['@t2-cuj', '@area:playground'],
}, () => {
  test(
    'every OpenRouter model the picker offers has a row in the shipped price file',
    { tag: ['@cap:playground.offered-model-price-coverage'] },
    async () => {
      // QA: failing on staging for the 2.3.2 release pass, and expected to.
      // Seven of the 372 labelled OpenRouter ids the deployment offers have no
      // row in `model_prices_openrouter.json`, so a span logged on any of them
      // is billed nothing: dots-studio/dots-3-note-preview:free,
      // mistralai/mistral-medium-3, mistralai/mistral-medium-3.1,
      // moonshotai/kimi-k2, moonshotai/kimi-k2-0905,
      // moonshotai/kimi-k2-thinking, xiaomi/mimo-v2.5.
      //
      // Cause established, and it is NOT a 2.3.2 regression. opik#9773
      // ("Update model prices file") landed on main AFTER the 2.3.2 version
      // bump and took the file from 476 rows to 470, removing exactly these
      // seven; at 2.3.2 itself all seven are present and this test is green.
      // The red here is the first thing the failure message tells a reader to
      // rule out — a checkout ahead of the deployment — except that the skew
      // runs the other way round for once: the QA branch carries post-release
      // main, and `llm-models-default.yaml` on that same main still offers all
      // seven ids. So this is a live money-to-zero defect on main heading for
      // 2.3.3, not an artefact of the branch.
      //
      // Marked rather than allowlisted, deliberately. An allowlist would retire
      // the relation this spec exists to pin — the unpriced set must be EMPTY,
      // which is what made the 2.3.0 failure a finding instead of a line of
      // maintenance. Remove `test.fail()` once a regen restores the rows (or a
      // catalog sync drops their labels); Playwright reports it when it passes.
      test.fail();

      // QA: was test.fail() for the 2.3.0 review pass, which reproduced the
      // defect this relation exists to catch — 1 of the 372 labelled OpenRouter
      // ids, `dots-studio/dots-3-note-preview:free`, was served by
      // `llm-models-default.yaml` WITH a label while no row in
      // `model_prices_openrouter.json` priced it, so a span logged on a model
      // the picker offers was billed nothing.
      //
      // Fixed in 2.3.1 by opik#9733's price regen, which added
      // `openrouter/dots-studio/dots-3-note-preview:free` to the file (476 rows
      // now carry it). Settled green on staging for the 2.3.1 pass, so the
      // marker is removed rather than kept: Playwright fails an
      // expected-to-fail test that passes.
      //
      // The assertion below is unchanged and is deliberately not an allowlist —
      // the unpriced set must be EMPTY. That is what made the 2.3.0 failure a
      // finding instead of a line of maintenance, and it is what will catch the
      // next regen that moves one file without the other.

      const rows = await test.step('Read the deployment’s own model registry', async () => {
        const registry = await fetchRegistryModels();
        const served = registry[PROVIDER];
        expect(
          Array.isArray(served),
          `the registry must serve an '${PROVIDER}' provider (it has: ${Object.keys(registry).join(', ')})`,
        ).toBe(true);
        return served!;
      });

      const priceKeys = await test.step('Read the shipped OpenRouter price file', async () => {
        const raw = JSON.parse(fs.readFileSync(OPENROUTER_PRICE_FILE, 'utf8')) as Record<
          string,
          unknown
        >;
        const keys = new Set(Object.keys(raw));
        // A file that failed to parse into rows would make every lookup below
        // miss and the failure would read as "the catalog lost its prices".
        expect(keys.size, `${OPENROUTER_PRICE_FILE} must carry price rows`).toBeGreaterThan(0);
        return keys;
      });

      const offered = rows.filter(listsInPicker);

      await test.step('The offered set is non-empty and really is a subset', async () => {
        // Both halves are the control. Without the first, a registry that
        // served no labelled row at all would satisfy every assertion below
        // while proving nothing. Without the second, a build that had stopped
        // filtering on `label` — the exact bug opik#9277 made visible — would
        // turn this into an assertion about all 826 rows and go red for a
        // reason that has nothing to do with prices.
        expect(offered.length, 'the picker must offer at least one OpenRouter model').toBeGreaterThan(
          0,
        );
        expect(
          offered.length,
          'some OpenRouter rows must be unlabelled, or `listsInPicker` is not discriminating ' +
            'and this spec is asserting over the whole catalog instead of the offered part',
        ).toBeLessThan(rows.length);
      });

      await test.step('Every offered id resolves to a price row', async () => {
        const unpriced = offered
          .filter((model) => !priceKeys.has(priceKeyFor(model.id)))
          .map((model) => model.id);

        expect(
          unpriced,
          `${unpriced.length} of ${offered.length} OpenRouter models the picker offers have no ` +
            `row in model_prices_openrouter.json, so a span logged on one is attributed no cost ` +
            `at all: ${JSON.stringify(unpriced)}. Before reading this as a regression, check ` +
            `that this checkout is the build the target deployment is serving — a model the ` +
            `deployment offers because it is NEWER than this checkout has no row here either.`,
        ).toEqual([]);
      });
    },
  );
});

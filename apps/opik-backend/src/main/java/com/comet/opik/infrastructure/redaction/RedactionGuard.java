package com.comet.opik.infrastructure.redaction;

import com.comet.opik.infrastructure.auth.WorkspaceUserPermission;
import jakarta.ws.rs.ForbiddenException;
import lombok.NonNull;
import lombok.experimental.UtilityClass;
import lombok.extern.slf4j.Slf4j;

/**
 * Refuses a response whose content masking cannot reach.
 * <p>
 * Masking happens where a content column becomes a {@code JsonNode}, which covers every response assembled from
 * the DAOs. Two responses are assembled some other way and would otherwise hand a caller the stored content
 * unmasked:
 * <ul>
 * <li>the dataset CSV export, generated by a background job with no caller to decide against, written to storage
 * once and then downloaded by callers whose permissions differ from each other and from the job's;</li>
 * <li>attachment download, which streams bytes that never become a {@code JsonNode}.</li>
 * </ul>
 * For those, refusing is the honest answer: withholding is the whole point of the feature, and a response that
 * cannot be masked cannot be withheld any other way. Refusing only bites while the feature is switched on and
 * the caller lacks the permission, so an install with the flag off is unaffected.
 * <p>
 * Agent Insights free-form SQL is deliberately <em>not</em> here. The caller chooses the projection, so a name or
 * a pattern can be walked past — but masking every string in the result cannot be, and it leaves counts and
 * grouping over non-content dimensions working. See {@code AnalyticsQueriesResource.maskIfRequired}.
 */
@Slf4j
@UtilityClass
public class RedactionGuard {

    /**
     * @param redactResponse the decision resolved for this caller, from {@code RequestContext}
     * @param what           named in the 403 so the caller learns which response was withheld, not merely that
     *                       something was
     * @throws ForbiddenException when this caller's responses are masked
     */
    public static void rejectUnmaskable(boolean redactResponse, @NonNull String what) {
        if (!redactResponse) {
            return;
        }

        log.info("Refusing '{}': response cannot be masked and the caller lacks '{}'", what,
                WorkspaceUserPermission.ORIGINAL_DATA_VIEW.getValue());

        throw new ForbiddenException(
                "%s returns stored content that cannot be masked. The '%s' permission is required to read it."
                        .formatted(what, WorkspaceUserPermission.ORIGINAL_DATA_VIEW.getValue()));
    }
}

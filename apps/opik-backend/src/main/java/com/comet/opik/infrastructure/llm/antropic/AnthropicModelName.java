package com.comet.opik.infrastructure.llm.antropic;

import com.comet.opik.infrastructure.llm.StructuredOutputSupported;
import lombok.Getter;
import lombok.RequiredArgsConstructor;
import org.apache.commons.lang3.StringUtils;

import java.util.Arrays;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * This information is taken from <a href="https://docs.anthropic.com/en/docs/about-claude/models">Anthropic docs</a>
 */
@Getter
@RequiredArgsConstructor
public enum AnthropicModelName implements StructuredOutputSupported {
    CLAUDE_SONNET_3_7("claude-3-7-sonnet-20250219"),
    CLAUDE_FABLE_5("claude-fable-5"),
    CLAUDE_FABLE_5_1("claude-fable-5-1"),
    CLAUDE_HAIKU_4_5("claude-haiku-4-5-20251001"),
    CLAUDE_OPUS_4_1("claude-opus-4-1-20250805"),
    CLAUDE_OPUS_4("claude-opus-4-20250514"),
    CLAUDE_OPUS_4_5("claude-opus-4-5-20251101"),
    CLAUDE_OPUS_4_6("claude-opus-4-6"),
    CLAUDE_OPUS_4_7("claude-opus-4-7"),
    CLAUDE_OPUS_4_8("claude-opus-4-8"),
    CLAUDE_OPUS_5("claude-opus-5"),
    CLAUDE_SONNET_4("claude-sonnet-4-20250514"),
    CLAUDE_SONNET_4_5("claude-sonnet-4-5"),
    CLAUDE_SONNET_4_5_20250929("claude-sonnet-4-5-20250929"),
    CLAUDE_SONNET_4_6("claude-sonnet-4-6"),
    CLAUDE_SONNET_5("claude-sonnet-5");

    private final String value;

    /**
     * API ids of the Anthropic models that accept sampling params (temperature/top_p/top_k).
     *
     * <p><strong>Why this names the capable models rather than the models that reject them.</strong>
     * It was the inverse — a set of adaptive-thinking ids — and that shape rotted twice:
     * {@code claude-opus-5} and {@code claude-fable-5} were classified on the frontend and never
     * added here, and {@code claude-fable-5-1} was missed on both sides. Newer Claude models
     * increasingly take no sampling params, so naming the capable ones makes the default the safe
     * one: a model added by the recurring "sync provider model definitions" chore is assumed to take
     * none until someone says otherwise, which omits a parameter rather than having the provider
     * reject the whole request with a 400.
     *
     * <p><strong>Why a standalone set and not a per-constant flag.</strong> The enum constant list
     * above is regenerated by that same chore (e.g. #7088, #7315, #7582). The generator emits every
     * model as a single-arg {@code NAME("value")} constant and has no notion of an extra capability
     * argument, so a per-constant flag (the original #7531 shape, {@code NAME("value", false)}) is
     * silently dropped on the next sync — which is exactly how #7582 reverted the adaptive-thinking
     * opt-out and reopened issue #7526. Keeping the capability here lets syncs add, remove and
     * reorder constants freely. Referencing the constants rather than duplicating the string
     * literals means a sync that renames or removes one breaks compilation instead of drifting.
     */
    private static final Set<String> SAMPLING_CAPABLE_MODEL_IDS = Set.of(
            CLAUDE_SONNET_3_7.value,
            CLAUDE_HAIKU_4_5.value,
            CLAUDE_OPUS_4_1.value,
            CLAUDE_OPUS_4.value,
            CLAUDE_OPUS_4_5.value,
            CLAUDE_OPUS_4_6.value,
            CLAUDE_SONNET_4.value,
            CLAUDE_SONNET_4_5.value,
            CLAUDE_SONNET_4_5_20250929.value,
            CLAUDE_SONNET_4_6.value);

    private static final Set<String> ALL_MODEL_IDS = Arrays.stream(values())
            .map(AnthropicModelName::getValue)
            .collect(Collectors.toUnmodifiableSet());

    /** Exposed so a provider-neutral check can reuse these lists rather than copying them. */
    public static Set<String> samplingCapableModelIds() {
        return SAMPLING_CAPABLE_MODEL_IDS;
    }

    public static Set<String> allModelIds() {
        return ALL_MODEL_IDS;
    }

    /**
     * Whether the model accepts sampling params. A model we recognise but have not marked capable
     * takes none. A name we cannot place at all stays permissive — it may be a capable Claude that a
     * proxy renamed, and silently dropping a temperature someone set is worse there than sending one.
     */
    public static boolean supportsSamplingParams(String modelName) {
        if (StringUtils.isBlank(modelName) || SAMPLING_CAPABLE_MODEL_IDS.contains(modelName)) {
            return true;
        }
        return !ALL_MODEL_IDS.contains(modelName);
    }

    @Override
    public String toString() {
        return value;
    }

    @Override
    public boolean isStructuredOutputSupported() {
        return false;
    }
}
